$converters = $highwaygroup = $invoices = array();

if (is_numeric($payment['MerchTxnRef'])) {
    $invoices[] = intval($payment['MerchTxnRef']);
} elseif (substr($payment['MerchTxnRef'], 0, 3) == 'HGR' || is_numeric(substr($payment['MerchTxnRef'], 0, 6)) || is_numeric(substr($payment['MerchTxnRef'], 15, 6)) || strpos($payment['MerchTxnRef'], 'Credit Transaction') !== false) {
    $use_field = 'ref';
    $ref       = substr($payment['MerchTxnRef'], 3);
    if (is_numeric(substr($payment['MerchTxnRef'], 0, 6))) {
        $ref       = intval(substr($payment['MerchTxnRef'], 0, 6));
        $use_field = 'id';
    } elseif (is_numeric(substr($payment['MerchTxnRef'], 15, 6))) {
        $ref       = intval(substr($payment['MerchTxnRef'], 15, 6));
        $use_field = 'id';
    } elseif (strpos($payment['MerchTxnRef'], 'Credit Transaction') !== false) {
        $ref       = intval(substr($payment['MerchTxnRef'], -6, 6));
        $use_field = 'id';
    }

    if ($query = $DB->query(sprintf(
        "SELECT * FROM `highwaygroup`.`credit_payments` WHERE `credit_%s` = %s",
        $use_field,
        $DB->escape($ref)
    ))) {
        while ($row = $DB->fetch_assoc($query)) {
            $highwaygroup[] = $row;
        }
        $DB->free_result($query);
    }
} else {
    if ($query = $DB->query(sprintf(
        "SELECT * FROM `converters`.`payment_notify` WHERE `payment_method` = 'CREDIT' AND `txn_id` = %s ORDER BY `date` ASC LIMIT 1",
        $DB->escape($payment['TransactionNo'])
    ))) {
        while ($row = $DB->fetch_assoc($query)) {
            $converters[] = $row;
        }
        $DB->free_result($query);
    }
}

if (preg_match('/invoice:([A-Z]+#)?([0-9]+)[A-Z]?/', $payment["MerchTxnRef"], $m)) {
    $invoices[] = intval(ltrim($m[2], '0'));
}
if (preg_match('/payment:([0-9]+)/', $payment["MerchTxnRef"], $m)) {
    if ($query = $DB->query(sprintf(
        "SELECT * FROM `highwaygroup`.`credit_payments` WHERE `credit_id` = %d",
        ltrim($m[1], '0')
    ))) {
        while ($row = $DB->fetch_assoc($query)) {
            $highwaygroup[] = $row;
        }
        $DB->free_result($query);
    }
}

